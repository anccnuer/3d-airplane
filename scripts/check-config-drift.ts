import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildGameData } from '../packages/shared/src/gameData';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'packages/shared/schema/game-protocol.json');
const schemaRaw = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(schemaRaw) as {
  version: number;
  magic: string;
  messages: Record<string, number>;
  envelope: Record<string, number>;
};
const hash = createHash('sha256').update(schemaRaw).digest('hex');
const goName = (name: string): string => name.replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase()).replace(/^./, (letter) => letter.toUpperCase());
const headerBytes = Object.values(schema.envelope).reduce((sum, value) => sum + value, 0);

const tsLines = [
  '// GENERATED FILE - DO NOT EDIT',
  `export const PROTOCOL_VERSION = ${schema.version};`,
  `export const PROTOCOL_MAGIC = ${JSON.stringify(schema.magic)};`,
  `export const PROTOCOL_SCHEMA_HASH = ${JSON.stringify(hash)};`,
  `export const ENVELOPE_HEADER_BYTES = ${headerBytes};`,
  'export const MessageType = {',
  ...Object.entries(schema.messages).map(([name, value]) => `  ${name}: ${value},`),
  '} as const;',
  'export type MessageTypeName = keyof typeof MessageType;',
  ''
];

const goLines = [
  '// Code generated by scripts/generate-protocol.ts. DO NOT EDIT.',
  'package generated',
  '',
  `const ProtocolVersion = ${schema.version}`,
  `const ProtocolMagic = ${JSON.stringify(schema.magic)}`,
  `const ProtocolSchemaHash = ${JSON.stringify(hash)}`,
  `const EnvelopeHeaderBytes = ${headerBytes}`,
  '',
  'const (',
  ...Object.entries(schema.messages).map(([name, value]) => `\tMessageType${goName(name)} = ${value}`),
  ')',
  ''
];

const checks: Array<[string, string]> = [
  ['packages/shared/src/generated/protocol.ts', tsLines.join('\n')],
  ['server/internal/protocol/generated/protocol.go', goLines.join('\n')],
  ['server/internal/config/game_data.json', `${JSON.stringify(buildGameData(), null, 2)}\n`]
];

try {
  for (const [file, expected] of checks) {
    const actual = readFileSync(resolve(root, file), 'utf8');
    if (actual !== expected) {
      throw new Error(`${file} is stale, run npm run proto:gen or npm run export:game-data`);
    }
  }
  console.log('config and protocol generated files are in sync');
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
