import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'packages/shared/schema/game-protocol.json');
const schemaRaw = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(schemaRaw) as {
  version: number;
  magic: string;
  messages: Record<string, number>;
  envelope: Record<string, number>;
};
const hash = createHash('sha256').update(schemaRaw).digest('hex');
const goName = (name: string): string => name.replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase()).replace(/^./, (letter) => letter.toUpperCase());

const tsTarget = resolve(root, 'packages/shared/src/generated/protocol.ts');
const goTarget = resolve(root, 'server/internal/protocol/generated/protocol.go');

mkdirSync(dirname(tsTarget), { recursive: true });
mkdirSync(dirname(goTarget), { recursive: true });

const tsLines = [
  '// GENERATED FILE - DO NOT EDIT',
  `export const PROTOCOL_VERSION = ${schema.version};`,
  `export const PROTOCOL_MAGIC = ${JSON.stringify(schema.magic)};`,
  `export const PROTOCOL_SCHEMA_HASH = ${JSON.stringify(hash)};`,
  `export const ENVELOPE_HEADER_BYTES = ${Object.values(schema.envelope).reduce((sum, value) => sum + value, 0)};`,
  'export const MessageType = {',
  ...Object.entries(schema.messages).map(([name, value]) => `  ${name}: ${value},`),
  '} as const;',
  'export type MessageTypeName = keyof typeof MessageType;',
  ''
];

const goLines = [
  '// Code generated by scripts/generate-protocol.ts. DO NOT EDIT.',
  'package generated',
  '',
  `const ProtocolVersion = ${schema.version}`,
  `const ProtocolMagic = ${JSON.stringify(schema.magic)}`,
  `const ProtocolSchemaHash = ${JSON.stringify(hash)}`,
  `const EnvelopeHeaderBytes = ${Object.values(schema.envelope).reduce((sum, value) => sum + value, 0)}`,
  '',
  'const (',
  ...Object.entries(schema.messages).map(([name, value]) => `\tMessageType${goName(name)} = ${value}`),
  ')',
  ''
];

writeFileSync(tsTarget, tsLines.join('\n'));
writeFileSync(goTarget, goLines.join('\n'));

console.log(`generated ${tsTarget}`);
console.log(`generated ${goTarget}`);
